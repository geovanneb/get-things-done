/** Return a supported character's bitmap, or the hollow replacement box. */
export function glyphFor(ch: string): Glyph {
  return Object.prototype.hasOwnProperty.call(FONT, ch) ? FONT[ch] : MISSING;
}

/** Width in pixels of `text` when rendered with 1px letter spacing. */
export function measureText(text: string): number {
  const count = Array.from(text).length;
  return count === 0 ? 0 : count * (GLYPH_W + 1) - 1;
}
